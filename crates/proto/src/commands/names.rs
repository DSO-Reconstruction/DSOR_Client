/// The class name of command `id`, as the 2018 client registers it.
pub fn command_name(id: u16) -> Option<&'static str> {
    COMMANDS.binary_search_by_key(&id, |c| c.0).ok().map(|i| COMMANDS[i].1)
}

/// Whether command `id` ends with the 32-bit actor (slot 9 = sub_A06021).
/// CONTRACT: an id missing from the table is treated as actor-scoped, like most.
pub fn actor_scoped(id: u16) -> bool {
    COMMANDS.binary_search_by_key(&id, |c| c.0).map(|i| COMMANDS[i].2).unwrap_or(true)
}

/// The id past which DrasaClientHandler::DecodeCommand refuses a command
/// (cmp r9w, 0x177 / jb), the Builtin chat command excepted.
pub const MOST_COMMANDS: u16 = 0x177;
